/**
 * Pre-compute the booleans the `session_analytics_tab_viewed`
 * event ships so the mount effect stays a one-liner. Pure: no
 * window access here.
 */
export function deriveTabMountProperties(
  items: ReadonlyArray<PerQuestionAnalytics>,
): {
  question_count: number;
  has_profile_leverage_suggestions: boolean;
  has_weak_star_signals: boolean;
} {
  return {
    question_count: items.length,
    has_profile_leverage_suggestions: items.some(
      (i) => i.profile_leverage.status === "available_unused",
    ),
    has_weak_star_signals: items.some((i) => hasWeakOrMissingStar(i)),
  };
}
