/* ────────────────────────────────────────────────────────────── */
/* Analytics-feature launch cutoff                                */
/* ────────────────────────────────────────────────────────────── */

/**
 * Hard cut-off used to decide whether a report SHOULD have been
 * generated with the current per-question-analytics prompt
 * section. The value mirrors the latest prompt bump in
 * `src/lib/llm/prompt.ts` (`SYSTEM_PROMPT_VERSION`) — every report
 * created at or after this instant ran against the current prompt
 * and, if `per_question_analytics` is still absent, the LLM
 * omitted it deliberately (genuinely empty / failed transcript,
 * `questionsCovered: []`).
 *
 * The cutoff was bumped to 2026-05-18 alongside the prompt
 * revision that started driving entries off `questionsCovered`
 * (the previous 2026-05-17 version required an artifact-backed
 * UUID per entry and therefore produced no analytics for sessions
 * whose questions were all transcript-inferred — see the prompt
 * comment header for the full history). Bumping the cutoff makes
 * reports written between 2026-05-17 and 2026-05-18 fall into the
 * "legacy" branch again so re-analyzing them under the new prompt
 * actually populates the charts.
 *
 * Used by the Analytics tab's `LegacyReportPlaceholder` to swap
 * the copy + CTA: pre-cutoff reports show the "click re-analyze"
 * message (re-analysis with the new prompt will fix them); post-
 * cutoff reports show a "we couldn't compute analytics" message
 * and DO NOT offer the re-analyze button (it wouldn't change
 * anything and would re-charge the user or burn their free 24h
 * slot for nothing).
 *
 * Exported so the runbook query, the unit tests, and the
 * placeholder all stay anchored on the same instant.
 */
export const ANALYTICS_FEATURE_LAUNCHED_AT = new Date(
  "2026-06-01T00:00:00.000Z",
);

/**
 * True when the report's `created_at` is at or after the analytics-
 * feature launch instant, i.e. the report was generated by the
 * current prompt and its absence of `per_question_analytics` is
 * informative ("the LLM ran the new section and chose not to emit
 * anything"), not legacy ("the prompt section didn't exist yet").
 *
 * Returns `false` when `reportCreatedAt` is `null` / `undefined`
 * so harness / Storybook renders fall through to the original
 * legacy-message branch — the pre-existing behavior when no date
 * is available.
 *
 * Pure / boundary-only: extracted from the React component file so
 * vitest can pin the cutoff semantics without spinning up a DOM
 * renderer (the project doesn't ship one — see the comment header
 * on `analytics-utils.test.ts`).
 */
export function isPostLaunchReport(
  reportCreatedAt: Date | null | undefined,
): boolean {
  if (reportCreatedAt == null) return false;
  return reportCreatedAt.getTime() >= ANALYTICS_FEATURE_LAUNCHED_AT.getTime();
}

/* ────────────────────────────────────────────────────────────── */
/* Time formatting                                                */
/* ────────────────────────────────────────────────────────────── */

/**
 * Format a duration in seconds as `M:SS`. Used by the per-question
 * card duration label and by the time-distribution bar's segment
 * title attributes.
 *
 * Floors the seconds and clamps the input non-negative so a
 * malformed `-1` doesn't render as `-1:0-1`. Matches the format
 * used by `formatMmSs` in `lib/analytics/narratives.ts` — kept as
 * a sibling rather than imported to keep this module free of
 * server-only transitive imports.
 */
export function formatMmSs(seconds: number): string {
  const safe = Math.max(0, Math.floor(seconds));
  const m = Math.floor(safe / 60);
  const s = safe % 60;
  return `${m}:${s.toString().padStart(2, "0")}`;
}

/* ────────────────────────────────────────────────────────────── */
/* STAR completeness summary line                                 */
/* ────────────────────────────────────────────────────────────── */

/**
 * Render the right-aligned summary line above each STAR bar
 * (e.g. "92% present, 8% weak"). Includes only non-zero segments
 * so a fully-present dimension reads "100% present" instead of
 * "100% present, 0% weak, 0% missing".
 *
 * Returns the empty string when the dimension has zero
 * contributors — the renderer can use that to skip the right
 * column entirely.
 */
export function formatStarSummary(totals: {
  present: number;
  weak: number;
  missing: number;
  total: number;
}): string {
  if (totals.total === 0) return "";
  const pct = (n: number): number => Math.round((n / totals.total) * 100);
  const parts: string[] = [];
  const presentPct = pct(totals.present);
  const weakPct = pct(totals.weak);
  const missingPct = pct(totals.missing);
  if (presentPct > 0) parts.push(`${presentPct}% present`);
  if (weakPct > 0) parts.push(`${weakPct}% weak`);
  if (missingPct > 0) parts.push(`${missingPct}% missing`);
  return parts.join(", ");
}

