/**
 * Tiny 8px coloured dot rendered on the LEFT of every collapsed
 * per-question row in place of the (deleted) confidence pill.
 *
 * Colour mapping follows the same semantic tokens the larger
 * pill used so a candidate already familiar with the previous
 * grammar reads the new dot the same way:
 *
 *   high   → success (green/teal)
 *   medium → warning (amber)
 *   low    → danger  (coral)
 *   null   → neutral grey (the row is paired with a coverage
 *            entry whose confidence we couldn't resolve, or the
 *            row is analytics-only on a legacy report)
 *
 * Returns CSS-variable references — the same tokens the STAR
 * badges use — so the colour stays in lockstep with the theme.
 */
export function confidenceDotColor(
  confidence: "high" | "medium" | "low" | null | undefined,
): string {
  switch (confidence) {
    case "high":
      return "var(--color-success)";
    case "medium":
      return "var(--color-warning)";
    case "low":
      return "var(--color-danger)";
    default:
      return "var(--color-text-tertiary)";
  }
}

/**
 * Accessible label / hover tooltip for the confidence dot.
 * Mirrors the (deleted) pill copy so screen-reader users get the
 * same wording across the previous and new surfaces.
 */
export function confidenceDotLabel(
  confidence: "high" | "medium" | "low" | null | undefined,
): string {
  switch (confidence) {
    case "high":
      return "High confidence";
    case "medium":
      return "Medium confidence";
    case "low":
      return "Low confidence";
    default:
      return "Confidence unknown";
  }
}

