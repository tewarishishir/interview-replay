/* ────────────────────────────────────────────────────────────── */
/* Profile leverage indicator                                     */
/* ────────────────────────────────────────────────────────────── */

/**
 * Resolved view of `profile_leverage` ready for the per-question
 * card to render. We do the noun-and-color decision here so the
 * card component stays focused on layout.
 *
 * `clickable: true` for `available_unused` only — that's the
 * status the spec wires to a Practice Rebuild launch with the
 * suggested item pre-selected. The other statuses are read-only
 * informational rows.
 */
export interface ProfileLeverageIndicator {
  text: string;
  color: string;
  clickable: boolean;
  suggestedItemId?: string;
}

export function formatProfileLeverage(
  leverage: ProfileLeverage,
): ProfileLeverageIndicator | null {
  switch (leverage.status) {
    case "used": {
      // We render even without a label so the candidate sees their
      // profile was used; the schema allows `referenced_item_label`
      // to be absent in pathological cases (older reports).
      const label = leverage.referenced_item_label ?? "a profile item";
      return {
        text: `Used ${label}`,
        color: "var(--color-success)",
        clickable: false,
      };
    }
    case "available_unused": {
      // The schema doesn't carry `suggested_item_type` directly —
      // we infer the noun from `referenced_item_type` when set
      // (the model sometimes emits both fields together) and
      // otherwise fall back to "story", which is the more common
      // surface in the rebuild flow.
      const noun =
        leverage.referenced_item_type === "project" ? "project" : "story";
      const label = leverage.suggested_item_label ?? "a stronger option";
      return {
        text: `Stronger ${noun} available: ${label}`,
        color: "var(--color-danger)",
        clickable: leverage.suggested_item_id !== undefined,
        suggestedItemId: leverage.suggested_item_id,
      };
    }
    case "no_match":
      return {
        text: "No matching profile content",
        color: "var(--color-text-tertiary)",
        clickable: false,
      };
  }
}

/* ────────────────────────────────────────────────────────────── */
/* Speech pace gauge math                                         */
/* ────────────────────────────────────────────────────────────── */

/**
 * Upper bound on the gauge's visible needle position. WPM values
 * above this still render their actual number in the centre text
 * — only the needle parks at the arc's right edge. Picked so the
 * three coloured bands (≤120 measured, 120-170 conversational,
 * 170-220 brisk) fit symmetrically across the 180° arc.
 */
export const SPEECH_PACE_GAUGE_MAX_VISIBLE_WPM = 220;

/**
 * Compute the gauge's three visible quantities from raw inputs.
 *
 * Returns `null` when there's no signal (zero duration OR zero
 * words). The component uses that null-return as its "don't
 * render" gate so the section above stays clean.
 *
 * `wpm` is the candidate-visible number rendered in the centre of
 * the gauge — derived without clamping so a 240 WPM round still
 * shows "240" even though the needle parks at 220.
 *
 * `visibleWpm` drives the needle position only. Clamped to
 * `[0, SPEECH_PACE_GAUGE_MAX_VISIBLE_WPM]`.
 *
 * `angleDegrees` maps `visibleWpm` to the rotation that takes the
 * needle from the left edge (-90°) to the right edge (+90°) over
 * the gauge's 180° arc. Linearly interpolated — the band
 * boundaries are visual (coloured stroke segments), not encoded
 * into the angle.
 */
export interface SpeechPaceGaugeMetrics {
  wpm: number;
  visibleWpm: number;
  angleDegrees: number;
}

/**
 * Physiological ceiling for human speech in WPM. The fastest
 * recorded auctioneers and speed-talkers peak around 400-450 WPM.
 * Anything above 500 is a data-quality problem (corrupted
 * durationSeconds, truncated audio, etc.) — we suppress the gauge
 * rather than show a meaningless five-digit number.
 */
export const SPEECH_PACE_MAX_PLAUSIBLE_WPM = 500;

export function computeSpeechPaceGaugeMetrics(
  wordCount: number,
  durationSeconds: number,
): SpeechPaceGaugeMetrics | null {
  if (wordCount <= 0 || durationSeconds <= 0) return null;
  const wpm = Math.round(wordCount / (durationSeconds / 60));
  // Guard against corrupted duration data (e.g. the transcription service returning
  // metadata.duration=15 for a 30-minute recording). Show nothing
  // rather than a physically impossible five-digit WPM.
  if (wpm > SPEECH_PACE_MAX_PLAUSIBLE_WPM) return null;
  const visibleWpm = Math.min(
    SPEECH_PACE_GAUGE_MAX_VISIBLE_WPM,
    Math.max(0, wpm),
  );
  const angleDegrees =
    -90 + (visibleWpm / SPEECH_PACE_GAUGE_MAX_VISIBLE_WPM) * 180;
  return { wpm, visibleWpm, angleDegrees };
}

/* ────────────────────────────────────────────────────────────── */
/* Coverage ↔ analytics matching                                  */
/* ────────────────────────────────────────────────────────────── */

/**
 * Normalise a question string for cross-array matching. The model
 * occasionally emits trivial whitespace / casing differences
 * between the `questionsCovered[i].question` string and the paired
 * `per_question_analytics[i].question_text` string (the latter is
 * "duplicated from the artifact for convenience" — see the schema
 * JSDoc — but the model is generative, not a memcpy). Collapsing
 * to a normalised key keeps the match robust without paying the
 * cost of a fuzzy-string library.
 */
function normaliseQuestionKey(text: string): string {
  return text.trim().toLowerCase().replace(/\s+/g, " ");
}

/**
 * Build a lookup table from normalised question text →
 * `QuestionCovered`. Returns `null` when the input is empty so the
 * caller can skip the per-card render path entirely.
 *
 * On a duplicate key (very rare — the model would have to emit two
 * questions that normalise to the same string), the FIRST entry
 * wins. The Analytics tab needs a single coverage record per
 * question and the order matches the report; preferring the first
 * keeps the rendered confidence stable across re-renders.
 */
export function buildCoverageLookup(
  coverage: ReadonlyArray<QuestionCovered> | undefined,
): ReadonlyMap<string, QuestionCovered> | null {
  if (!coverage || coverage.length === 0) return null;
  const map = new Map<string, QuestionCovered>();
  for (const q of coverage) {
    const key = normaliseQuestionKey(q.question);
    if (!map.has(key)) map.set(key, q);
  }
  return map;
}

/**
 * Resolve the `QuestionCovered` row that pairs with a given
 * per-question analytics entry. Lookup is by normalised question
 * text (see `buildCoverageLookup`). Returns `null` when no match
 * is found — older reports lack a `questionsCovered` array, and
 * the rare case where the model's two strings drift enough that
 * normalisation can't reconcile them. The card simply hides the
 * confidence / source pills in that case rather than picking the
 * wrong row.
 */
export function findCoverageMatch(
  item: PerQuestionAnalytics,
  lookup: ReadonlyMap<string, QuestionCovered> | null,
): QuestionCovered | null {
  if (lookup === null) return null;
  return lookup.get(normaliseQuestionKey(item.question_text)) ?? null;
}

/**
 * Mirror of `buildCoverageLookup` for `per_question_analytics`.
 * Used by the merged "Questions covered & Analytics" tab to walk
 * `questionsCovered` as the primary axis and pull the paired
 * analytics row for each entry. First-emitter wins on the rare
 * duplicate-key case, matching the coverage helper's contract.
 *
 * Returns `null` when the input is empty / undefined so the
 * caller can short-circuit the pairing loop.
 */
export function buildAnalyticsLookup(
  items: ReadonlyArray<PerQuestionAnalytics> | undefined,
): ReadonlyMap<string, PerQuestionAnalytics> | null {
  if (!items || items.length === 0) return null;
  const map = new Map<string, PerQuestionAnalytics>();
  for (const item of items) {
    const key = normaliseQuestionKey(item.question_text);
    if (!map.has(key)) map.set(key, item);
  }
  return map;
}

/**
 * Resolve the `PerQuestionAnalytics` entry paired with a given
 * `QuestionCovered` row. Symmetric counterpart of
 * `findCoverageMatch` — used by the merged-list builder so each
 * coverage row can pull in its STAR badges, metrics, and Rebuild
 * affordance from the analytics array. `null` for coverage rows
 * the analytics array doesn't carry (legacy report, post-launch
 * "LLM dropped this row", string drift) — the row renders in
 * coverage-only mode (pills + evidence quote, no STAR / metrics).
 */
export function findAnalyticsMatch(
  coverage: QuestionCovered,
  lookup: ReadonlyMap<string, PerQuestionAnalytics> | null,
): PerQuestionAnalytics | null {
  if (lookup === null) return null;
  return lookup.get(normaliseQuestionKey(coverage.question)) ?? null;
}

/**
 * Re-export the question-key normaliser so the merged-list
 * builder can mark analytics entries as "consumed" by their
 * normalised key when scanning for orphans. Kept internal-feeling
 * by lowercase naming; the merged-tab subtree is the only intended
 * caller outside this module.
 */
export function questionKey(text: string): string {
  return normaliseQuestionKey(text);
}

