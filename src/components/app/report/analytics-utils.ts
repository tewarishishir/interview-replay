/* STAR badge style + label                                       */
/* ────────────────────────────────────────────────────────────── */

export type StarDimensionKey = "situation" | "task" | "action" | "result";

const STAR_LETTERS: Record<StarDimensionKey, string> = {
  situation: "S",
  task: "T",
  action: "A",
  result: "R",
};

const STAR_LABELS: Record<StarDimensionKey, string> = {
  situation: "Situation",
  task: "Task",
  action: "Action",
  result: "Result",
};

/**
 * Return the single-letter abbreviation used on the per-question
 * card's badges. Kept as a function (not a constant lookup) so the
 * call sites read the same way the four-dimension iteration does.
 */
export function starLetterFor(dim: StarDimensionKey): string {
  return STAR_LETTERS[dim];
}

export function starLabelFor(dim: StarDimensionKey): string {
  return STAR_LABELS[dim];
}

/**
 * Shape for the per-dimension badge on a `MergedQuestionRow`. Drives
 * the badge's background color, text color, and trailing glyph.
 *
 * Tests pin the glyph + class shape so a copy-edit on the card
 * doesn't accidentally drop the visual delta between present /
 * weak / missing.
 */
export interface StarBadgeStyle {
  /** Glyph trailing the letter — ✓ / ⚠ / ✗. */
  glyph: string;
  /** Inline-style background color reference. */
  background: string;
  /** Inline-style text color reference. */
  color: string;
}

const STAR_BADGE_PRESENT: StarBadgeStyle = {
  glyph: "✓",
  background: "var(--color-success-bg)",
  color: "var(--color-success-text)",
};
const STAR_BADGE_WEAK: StarBadgeStyle = {
  glyph: "⚠",
  background: "var(--color-warning-bg)",
  color: "var(--color-warning-text)",
};
const STAR_BADGE_MISSING: StarBadgeStyle = {
  glyph: "✗",
  background: "var(--color-danger-bg)",
  color: "var(--color-danger-text)",
};

/**
 * Map a STAR signal value to its rendered-badge style. Returns
 * `null` for `'na'` so the caller can choose to omit the badge
 * (we render the `N/A` aggregate badge separately when ALL four
 * are 'na' — see `isAllNa`).
 */
export function starBadgeStyleFor(value: StarSignal): StarBadgeStyle | null {
  switch (value) {
    case "present":
      return STAR_BADGE_PRESENT;
    case "weak":
      return STAR_BADGE_WEAK;
    case "missing":
      return STAR_BADGE_MISSING;
    case "na":
      return null;
  }
}

/**
 * True when every STAR dimension on this entry is `'na'` — the
 * card renders a single "N/A" badge in that case rather than four
 * individual badges (none of which would convey signal).
 */
export function isAllNa(item: PerQuestionAnalytics): boolean {
  const s = item.star_signals;
  return (
    s.situation === "na" &&
    s.task === "na" &&
    s.action === "na" &&
    s.result === "na"
  );
}

/**
 * True when at least one STAR dimension is 'weak' or 'missing' on
 * a scoreable entry. Drives the "Rebuild this answer" affordance
 * on per-question cards.
 */
export function hasWeakOrMissingStar(item: PerQuestionAnalytics): boolean {
  if (isAllNa(item)) return false;
  const s = item.star_signals;
  return (
    s.situation === "weak" ||
    s.situation === "missing" ||
    s.task === "weak" ||
    s.task === "missing" ||
    s.action === "weak" ||
    s.action === "missing" ||
    s.result === "weak" ||
    s.result === "missing"
  );
}

/* ────────────────────────────────────────────────────────────── */
/* Answer-length target-band geometry                              */
/* ────────────────────────────────────────────────────────────── */

/**
 * Compute the 90s–180s target band's vertical geometry for the
 * answer-length distribution chart.
 *
 * The band is rendered as a HORIZONTAL stripe across the full
 * chart width — its bottom edge sits at the y-position
 * corresponding to 90s and its top edge at 180s, both expressed
 * as percentages of the chart's vertical scale (0 → maxDuration).
 * The percentage values match the CSS positioning we use:
 *
 *   bottom: `${bottomPct}%`   // distance from chart floor to 90s
 *   height: `${heightPct}%`   // span between 90s and 180s
 *
 * Clamping rules — both intentional, both keep the band visible
 * even when the data is degenerate:
 *
 *   1. `maxDuration <= 0` (defensive — the analyze pipeline
 *      guarantees positive durations) → use 1 so the math is
 *      finite and the caller still renders SOMETHING the user
 *      can read.
 *   2. `maxDuration < 180` → the 180s edge would otherwise sit
 *      above the chart top. We clamp the top edge to 100% so the
 *      band reads as "every bar of this short interview is in or
 *      below target", visually pinned at the chart top rather
 *      than scrolling off-screen.
 *   3. `maxDuration < 90` (rare; only happens when EVERY answer
 *      was under 90s) → bottom AND top both clamp to 100%; the
 *      band collapses to a single zero-height line at the chart
 *      top. The renderer can skip drawing the band in that case
 *      since `heightPct === 0`.
 *
 * Pure: no DOM / style imports. The pixel-space conversion lives
 * in the renderer (it knows how much of the chart height is
 * reserved for the bottom label rail).
 */
export interface AnswerLengthBandGeometry {
  /** Distance from chart floor to the 90s line, as % of chart height. */
  bottomPct: number;
  /** Distance from chart floor to the 180s line, as % of chart height. */
  topPct: number;
  /** Span between 90s and 180s, as % of chart height. May be 0. */
  heightPct: number;
}

export const ANSWER_LENGTH_LOWER_TARGET_S = 90;
export const ANSWER_LENGTH_UPPER_TARGET_S = 180;

export function computeAnswerLengthBandGeometry(
  maxDurationSeconds: number,
): AnswerLengthBandGeometry {
  const safeMax = maxDurationSeconds > 0 ? maxDurationSeconds : 1;
  const bottomPct = Math.min(
    100,
    (ANSWER_LENGTH_LOWER_TARGET_S / safeMax) * 100,
  );
  const topPct = Math.min(
    100,
    (ANSWER_LENGTH_UPPER_TARGET_S / safeMax) * 100,
  );
  const heightPct = Math.max(0, topPct - bottomPct);
  return { bottomPct, topPct, heightPct };
}

