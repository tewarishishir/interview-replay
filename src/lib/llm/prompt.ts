/**
 * The system prompt for InterviewReplay report generation. This file is the
 * load-bearing source of "what kind of feedback InterviewReplay produces"
 * — every change here ripples through every subsequent report,
 * so we bump `SYSTEM_PROMPT_VERSION` in lockstep with the body.
 *
 * The product position the prompt enforces:
 *
 *   1. We are a COACHING tool, not a hiring committee. Reports
 *      are written to the candidate, in the second person, to
 *      improve their NEXT interview.
 *   2. We do NOT predict pass/fail. Hard rule. The
 *      `lib/llm/forbidden.ts` regex catches lapses; the worker
 *      retries once and surfaces a validation error if the model
 *      can't comply.
 *   3. Every claim is anchored in evidence — a quote, an
 *      observable behavior — not vibes.
 *   4. Improvements come with concrete, actionable next steps
 *      ("rehearse the STAR situation in 1 sentence" — not "be
 *      more concise").
 */

// Bumped 2026-05-31.v4: strengthened executiveSummary vs. aiRead
// differentiation. Replaced the old 2-sentence guidance with explicit
// section definitions (InterviewReplay'ed read: 3-5 sentences / Executive Summary:
// 4-7 sentences), an example failure mode, and a hard differentiation test
// applied to Executive Summary sentences rather than aiRead sentences.
// The overlap detection in analyze-session.ts was updated in lockstep:
// 5-word n-grams (was 3), overlap coefficient (was Jaccard), thresholds
// >0.35 retry / >0.20 warning (was >0.30 / >0.15), and audit events are
// now written for both retry and warning cases.
//
// Bumped 2026-05-31.v3: added dedicated "InterviewReplay'ed read — opening sentence"
// section with explicit forbidden-opener list and five alternative structures
// (A–E). The post-generation retry logic in the analyze worker checks
// `hasFormulaicOpening` on the first-attempt paragraph and injects a targeted
// re-write instruction when the LLM defaults to the templated 'Your X is Y…'
// pattern. See also `src/lib/sessions/analyze-inline.ts`.
//
// Bumped 2026-05-18.v1: per_question_analytics is now driven off
// `questionsCovered` instead of the artifact list. The previous
// version (2026-05-17.v1) required every entry to carry an
// `artifact_id` UUID copied from the prompt's artifact header,
// which meant transcript-inferred questions (no backing artifact
// row) could never produce an entry — and a session whose
// questions were ALL transcript-inferred ended up with no
// per_question_analytics at all. The Analytics tab then showed the
// "we couldn't compute analytics for this round" empty state on
// what should have been a populated chart. The new prompt asks for
// one entry per `questionsCovered` row (high / medium / low
// confidence alike), with `artifact_id` populated only when the
// question is backed by an actual artifact UUID — see the
// per_question_analytics section below for the sourcing rule.
//
// 2026-05-17.v1: added the top-level `per_question_analytics`
// array — a per-answer structured breakdown the new Analytics tab
// renders (STAR completeness chart, answer-length bands, time
// distribution, pace gauge). The model emits one entry per
// confirmed-or-high-confidence-inferred question. Fields are pinned
// in the schema (`perQuestionAnalyticsSchema`); the prompt section
// below tells the model how to compute each one, anchored against
// the candidate's profile snapshot we now splice in. The whole
// array is OPTIONAL on the schema so a model that can't produce it
// for a thin transcript can fall back to omitting it without
// failing validation (the post-response guardrails then strip it
// rather than retry forever).
//
// 2026-05-09.v2: each `improvements[]` item now carries a
// `rebuildEligible: boolean` flag the model decides during analysis.
// The report view uses it to render an inline "Rebuild a story for
// this →" button under exactly the improvements that benefit from
// a structured rewrite-and-critique loop, replacing the bottom-of-
// report "Strengthen your story bank" section that used to duplicate
// the same insights. Eligibility is the model's call (not a regex
// over the heading) because the model has the full context — story
// shape, round type, what the gap actually is — and a regex would
// either over-trigger ("we" inside a coding-round comment) or
// under-trigger (a structural-rewrite improvement phrased without
// any of the trigger words).
//
// 2026-05-09.v1: added `questionsCovered` — an authoritative
// per-report list of the questions the candidate was asked, each
// with a confidence band ('high' | 'medium' | 'low') and a source
// tag ('candidate_confirmed' | 'transcript_inferred'). This is the
// load-bearing fix for "the upstream Haiku review pass returned
// zero suggestions, so the candidate had no question list at all
// to anchor the report against". Sonnet has the full transcript
// AND any candidate-supplied / AI-inferred artifacts and can
// always produce this list — even on heavily-redacted or otherwise
// noisy transcripts where Haiku gave up.
//
// 2026-05-08.v2: artifact headers now carry explicit
// provenance ("user-added", "AI-inferred candidate-confirmed",
// "AI-inferred best-guess (high|medium confidence) not yet
// confirmed"). This prompt now tells the model how to weight each
// band so it stops calling out "the candidate did not supply the
// full question list" when Haiku has actually surfaced 4-6
// inferred questions the candidate just hasn't confirmed.
//
// 2026-05-08.v1: added `aiRead.readinessScore` (0-100) — a
// preparedness rating for THIS round at the candidate's stated level.
// Explicitly NOT a hire/no-hire prediction (the existing hard rules
// and the `forbidden.ts` regex still hold; the field measures
// performance against the rubric, not odds of being hired).
//
// 2026-05-07: pinned the per-round-kind schema for `roundSpecific`
// (fixes LlmValidationError: roundSpecific.starCompleteness expected
// string, received undefined — the model was inventing field names like
// `starAnalysis` / `conflictCollaboration` because the prior version of
// this prompt only said `{ ...keyed by "kind" }`).
//
// 2026-05-31.v5: reframed roundSpecific as a DIAGNOSTIC SCORECARD.
// Each dimension is now a structural measurement (distribution, count,
// inventory, presence/absence), not a critique or prescription. Critique
// lives in Improvements; evaluation of specific moments lives in Strengths.
// Universal rule: prescriptive language ("you should", "try to",
// "could improve") is forbidden in roundSpecific fields.
//
// 2026-06-01.v1: rollback — removed improvement category classification,
// filler-evidence cap, and per-question one_line_read. Prompts 2, 4, 5,
// 7, 8 remain in place.
